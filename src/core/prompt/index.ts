// =============================================================================
// 中台通用提示词工程层（Prompt Kit）
//
// 目的：把"agent harness"级提示词工程沉淀为中台可复用的原语，任何项目都能
// 组合出结构一致、纪律清晰的 system prompt，而不是各自堆一段扁平散文。
//
// 分层约定：
//   1. 平台层（server.ts）拼装"跨项目通用纪律"：工具优先、上下文压缩、结构化输出。
//   2. 项目层（projects/*/prompts.ts）用自己的协议原语组装"角色/能力/领域规则"。
// 所有 section 都通过 composePrompt 合并，空段自动剔除，顺序即优先级。
// =============================================================================

// -- 组装原语 -------------------------------------------------------------

/** 把若干提示片段按顺序合并成一段 prompt，空/假值自动剔除，段间空一行。 */
export function composePrompt(
  parts: Array<string | undefined | false | null>
): string {
  return parts
    .filter((p): p is string => typeof p === "string" && p.trim().length > 0)
    .join("\n\n")
    .trim();
}

/** 生成一个标题段： `# 标题\n正文`。 */
export function section(title: string, body: string): string {
  return `# ${title}\n${body.trim()}`;
}

// -- 平台层通用纪律（server.ts 组装用） ------------------------------------

/** 工具优先纪律：外部确定性 > 内部猜测。 */
export function toolFirstProtocol(): string {
  return "[工作纪律]\n" +
    "1. 事实来自工具：任何具体数据（数字、状态、记录）必须来自工具结果，禁止凭记忆或推测给出。\n" +
    "2. 关键结论交叉验证：重要判断（尤其涉及具体数值）建议用第二个工具或重查确认，不单凭一次结果。\n" +
    "3. 不做无意义重复查询：已查过的相同信息不反复调用同一工具。\n" +
    "4. 区分问题类型：需要真实数据/事实的问题必须先走工具拿到结果再作答；" +
    "但开放性问题（起草文案、解释概念、给建议、头脑风暴、归纳总结）可以直接用推理回答，不必强行调用工具。";
}

/** 思考语言约定：让模型内部推理（思考体）尽量用与用户一致的中文，而非默认英文。 */
export function thinkingLanguageGuide(): string {
  return (
    "[思考语言]\n" +
    "你的思考/推理过程（reasoning/思考体）请一律使用中文。用户用中文提问，就用中文思考，" +
    "措辞口语化、有内部独白的自然感；不要切换成英文推理，除非主题本身强依赖英文专有名词。"
  );
}

/** 上下文管理约定：工具结果外置为 {ref, summary}，按需 getArtifact 取回。 */
export function compactionProtocol(): string {
  return "[上下文管理约定]\n" +
    "1. 工具结果默认完整内联：只要返回的是完整数据对象（没有 ref / full:false 标记），" +
    "就说明你已经拿到全量数据，直接基于它作答即可，**不要为此重发同一查询**。" +
    "2. 仅当结果以 {ref, toolName, summary, full:false} 返回、或折叠占位明确带 ref=art-xxx 时，" +
    "才说明你手上只有摘要，需要细节才调用 getArtifact(ref) 取回完整数据。" +
    "3. 占位里没有 ref 时说明未持久化、无法取回，直接基于摘要推进。" +
    "4. 优先基于已有信息推进任务，不要重复查看相同内容，不要在没有有效 ref 时调用 getArtifact。\n" +
    "5. **外置即终点（终止协议）**：一旦结果外置（full:false 带 ref），说明数据已安全存好、" +
    "重查只会得到同一份。此时**禁止再次调用原查询工具**（同签名重查会被去重拦截），" +
    "唯一正确动作是 getArtifact(ref) 取回（可反复取、取回不算重复查询），然后基于取回的数据作答。" +
    "分页场景同理：翻完当前页 footer 指示的 offset 即可续取，但**绝不为了\"凑全量\"连续翻页拉完整数据集**。";
}

/** 结构化输出约定：需要结构化呈现时在回复文本内联 <render>{json}</render>。 */
export function structuredOutputGuide(): string {
  return "[结构化输出]\n" +
    "要把内容结构化呈现给用户（表格、指标卡、图表、Mermaid、文档、选项按钮、Markdown 等）时，" +
    "**只能用一种方式：把 <render>...</render> 当作普通文本，原样写进你的回复正文，前端统一解析渲染**。" +
    "**呈现不是工具调用**：不要调用任何名为 render 的工具或函数来呈现内容——" +
    "即使工具列表里出现一个叫 render 的兜底护栏，它也不是渲染通道，正常回答永远不该调用它；" +
    "也不要输出 `render{...}` 或 `render(...)` 这种像函数调用的形状。" +
    "结构块就是文本里的一对 `<render>...</render>` 标签，{json} 是那个数组的占位说明，不是真去写 `{json: ...}`。\n" +
    "一个可复制的示例：\n" +
    "```\n<render>[{\"kind\":\"table\",\"columns\":[{\"key\":\"name\",\"label\":\"业务员\"}],\"rows\":[{\"name\":\"潘锡麟\"}]}]</render>\n```\n" +
    "一次可声明多个块（如先卡片总览、再表格明细）。\n" +
    "**引用必须成真**：永远不要说\"见上表/见下图/如下表所示\"，除非该表格/图表已实际以 markdown 或 <render> 块给出；" +
    "要展示的数据就实实在在地给出来，不要只描述而缺失实体。\n" +
    "提供用户可选方向时，选项也**一律写成 <render>{json} choices 块**（见「选项使用规范」），" +
    "不要把它降级成探在正文里的纯文本问句。\n" +
    "表格/图表/指标卡这类结构化数据，优先用 <render> 声明（前端渲染为原生表格/图表组件）。";
}

/** 选项（choices）使用规范：何时用、怎么写、如何避免循环与菜单陷阱。 */
export function choicesProtocol(): string {
  return section(
    "选项（choices）使用规范",
    [
      "**定位**：选项块是「建议回复」，像 Claude 的建议按钮——帮用户省打字，不是强制菜单。",
      "**何时给选项（仅限以下场景）**：",
      "  a) 歧义澄清：用户请求可作多种理解，需用户确认口径（如「8月的单」→ 按工单日期 / 按状态变更日期）。",
      "  b) 下一步收敛：你已给出结果（表格/图表/指标卡），用户可能想继续深入某几个具体方向（如查完本月汇总 → 按业务员拆分 / 按客户 TOP10 / 汇款对比）。这是「结果 → 下一步」的收尾：结果渲染块之后，紧跟一个 choices 块，prompt 用承上启下的继续口吻（如「接下来想怎么看？」），并给尚未探索的方向，不要重复刚做的事。",
      "  c) 空对话引导：新对话开始时，给 2-3 个常见入口帮助用户上手。",
      "**何时不给选项**：",
      "  - 意图单一可直接回答时（如「查 SO-xxx」「本月有多少笔汇款」）—— 直接查、直接答，不要反问。",
      "  - 用户已在特定路径上深入时（如正在看某客户的订单明细）—— 不要打断，等用户主动提新需求。",
      "**数量与文案**：2-3 个最佳，最多 4 个。label 动词开头、具体可执行（「按业务员拆分」「看汇款明细」），不要空泛的「是/否/更多/其他」—— 模型收到这类选项后不知道该做什么，会再反问，形成循环。",
      "**结构字段**：给 choices 块一个 `header`（最多 12 字的语义短标签，如「查询口径」「时间范围」），渲染成问题上方的小 chip，帮用户分类；每项 `label` 要短、配一句 `description` 讲清口径/取舍；有推荐项时放第一位并标 `recommended: true`。",
      "**一层深度原则**：用户从选项中选了一个后，你直接给出结果或回答，不要再抛新一轮选项。除非出现了新的、真正的歧义（用户换了完全不同的话题方向），否则不要连续两轮都带选项。对话不能变成菜单导航。",
      "**不要重复已执行的选择**：如果用户已通过 CHOICE_SELECT 选择了某个方向（如\"按业务员拆分\"），回复完成后不要在下一轮建议中再次出现\"按业务员拆分\"。建议应指向尚未探索的方向。",
      "**dismissPolicy（消失策略）**：",
      "  - 歧义澄清场景用 on_select（用户选择后立即消失）。",
      "  - 建议回复场景用 on_type（用户开始打字时消失，给用户自由表达空间）。",
      "  - 缺省不填时按 on_select 处理。",
    ].join("\n"),
  );
}

// -- 项目层通用协议原语（projects/*/prompts.ts 组装用） -------------------

export interface AgentProtocolOptions {
  persona: string;
  mission?: string;
  capabilities?: string[];
  boundaries?: string[];
}

/** Agent 角色协议：定位、使命、能力边界。 */
export function agentProtocol(opts: AgentProtocolOptions): string {
  const body = [
    opts.persona,
    opts.mission ? `\n使命：${opts.mission}` : "",
    opts.capabilities?.length
      ? `\n你能做：\n${opts.capabilities.map((c) => `- ${c}`).join("\n")}`
      : "",
    opts.boundaries?.length
      ? `\n边界：\n${opts.boundaries.map((b) => `- ${b}`).join("\n")}`
      : "",
  ]
    .filter(Boolean)
    .join("\n");
  return section("角色与边界", body);
}

/** 推理协议：先判断问题类型，再决定"直接推理 or 走工具"，遇到歧义先澄清。 */
export function reasoningProtocol(): string {
  return section(
    "推理与决策",
    "1. **先判型再动手**：读懂用户到底要什么。需要真实数据/事实（数量/金额/状态/记录/统计）→ 判为查询类，必须走工具；" +
      "起草/解释/建议/归纳/头脑风暴 → 开放式，可直接推理回答。\n" +
      "2. **遇到歧义先澄清，不猜**：若问题可作多种理解（如只说\"8月的单\"未指出凭单日期还是状态日期），" +
      "按「选项使用规范」给出选项让用户确认，或明确说明你采用的假设再作答，不要默默选一种就往下算。\n" +
      "3. **最小工具足迹**：能用一个工具解决问题就不要连锁调用多个；列表够用就不拉详情。\n" +
      "4. **先总结再展开**：先给出一句话结论，再列出依据或明细，避免用户必须读完长文才知道答案。\n" +
      "5. **用中文思考**：你的思考/推理过程保持中文，与用户的提问语言一致，除非主题强依赖英文专有词。"
  );
}

export interface ToolProtocolOptions {
  /** 列出各工具的"何时用/何时不用"（项目可选传入）。 */
  usage?: string[];
  /** 强制约定，如"统计必须走聚合工具"。 */
  rules?: string[];
}

/** 工具使用协议：怎么选、怎么读结果、何时足够。 */
export function toolProtocol(opts: ToolProtocolOptions = {}): string {
  const body = [
    ...(opts.rules?.map((r) => `- ${r}`) ?? []),
    ...(opts.usage?.map((u) => `- ${u}`) ?? []),
    "- **读结果要落地**：工具返回什么就报什么，不要放大或臆测。返回为空/无数据就明说\"未查到\"，不要编造占位。",
    "- 一次 run 内优先一次性拿够所需数据；数据不足时评估是否需要补一次或有歧义需要再确认，随后收束。",
  ].join("\n");
  return section("工具使用协议", body);
}

/** 输出协议：答案的形态与可读性，以及何时用 render 块承载结构。 */
export function outputProtocol(opts: { tone?: string } = {}): string {
  const tone = opts.tone || "用中文，专业、克制、直接；关键数字突出。";
  return section(
    "输出约定",
    `- ${tone}\n` +
      "- 结构优先：结论在前，明细在后；能分组就分组，避免一大段黏在一起。\n" +
      "- **只要用户要求\"表格/对比/列表/汇总\"呈现多行数据，或回答里自然有多行结构化数据，就必须真正输出一个表格**，" +
        "用 `<render>` 内联块声明（字段 kind=table，columns+rows），绝不用文字描述代替。\n" +
      "- **表格的覆盖范围必须诚实**：当 rows 只是全量的一部分（如分页首页、Top N 采样）时，" +
        "表格块必须带 `total`（口径命中总数）、`truncated:true` 与 `footer`（覆盖说明），" +
        "让用户清楚\"当前展示 N-M 条、共 T 条\"；rows 就是完整结果集时省略这些字段。\n" +
      "- 指标概览用 cards 块，选项用 choices 块；图表类用 chart 块。\n" +
      "- **禁止悬空引用**：不要写\"见上表/见图/如下\"这类话却拿不出实际内容；要么真实给出表格/图表，要么不提。\n" +
      "- 金额/数量以接口返回为准，保留原币种与精度；不确定就标注。\n" +
      "- 输出顺序：先一句话结论，再渲染块（table/cards/chart），最后 1-3 行要点说明。\n" +
      "- 如果本轮回复已带选项，下一轮用户选择后不要再次输出选项（除非出现新歧义）。连续两轮选项会打断对话节奏。"
  );
}

/** 收束协议：何时停、避免空转。 */
export function terminationProtocol(): string {
  return section(
    "收束与防空转",
    "- 若已拿到所需数据但仍不足以回答，明说缺什么、怎么补，然后停止，不要反复重查。\n" +
      "- 若需求超出你的能力边界（不在上述能力/工具清单内），如实说明你能做什么、什么不支持，建议用户去对应系统页面处理。\n" +
      "- 不做无意义的重复工具调用；确认信息不足或超出能力后，立即给出结论并收束。\n" +
      "- 结果外置（full:false 带 ref）后拿到的 ref 是唯一句柄：要细节就 getArtifact 取回、然后作答收束；" +
      "绝不重发同一查询、绝不翻页硬拉全量。"
  );
}
